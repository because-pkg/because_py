"""
Code generation module: produces human-readable Python source strings
representing the compiled NumPyro model for auditing, export, or inspection.
"""

def generate_model_code_string(builder, data_shapes=None):
    """
    Returns a self-contained, executable Python source string that
    represents the NumPyro model built by generate_model_function().

    :param builder: NumPyroBuilder instance.
    :param data_shapes: Optional dict mapping variable names to their shapes.
    :return: str — a Python source string.
    """
    topo_order = builder.graph.get_topological_order()
    equations_dict = builder.parsed_equations
    families = builder.family_dict
    det_terms = builder.deterministic_terms
    cor_mats = builder.cor_matrices

    lines = []
    lines.append("# Auto-generated NumPyro model from because-py")
    lines.append("# -----------------------------------------------")
    lines.append("# This script is provided for inspection / customisation.")
    lines.append("# Covariance matrices and data arrays must be supplied")
    lines.append("# as keyword arguments when calling numpyro_model().")
    lines.append("")
    lines.append("import jax")
    lines.append("import jax.numpy as jnp")
    lines.append("import numpy as np")
    lines.append("import numpyro")
    lines.append("import numpyro.distributions as dist")
    lines.append("")

    # Build function signature
    all_vars = list(topo_order)
    struct_args = [f"L_{k}=None" for k in cor_mats.keys()]
    sig_parts = all_vars + struct_args + ["**kwargs"]
    lines.append(f"def numpyro_model({', '.join(sig_parts)}):")
    lines.append("    \"\"\"NumPyro causal model — generated by because.\"\"\"")
    lines.append("    computed_vars = {k: v for k, v in locals().items() if v is not None}")
    lines.append("    N = len(next(v for v in [" +
                 ", ".join(all_vars) + "] if v is not None))")
    lines.append("")

    def ind(n=1):
        return "    " * n

    pinned = set()

    # Generated string for MAG Induced correlations
    induced_cor_set = set()
    induced_err_vars = {}
    if builder.latent_method == "correlation" and getattr(builder, "induced_correlations", None):
        lines.append(f"{ind()}# --- MAG Induced Correlations (direct sigma_res parameterization) ---")
        lines.append(f"{ind()}# Each pair gets independent sigma_res for the shared latent component.")
        lines.append(f"{ind()}# Variables retain their own independent sigma for remaining residuals.")
        lines.append("")

        for pair in builder.induced_correlations:
            induced_cor_set.add(pair[0])
            induced_cor_set.add(pair[1])

        for pair in builder.induced_correlations:
            var1, var2 = pair[0], pair[1]
            pair_tag = f"{var1}_{var2}"

            if var1 not in induced_err_vars:
                induced_err_vars[var1] = []
            if var2 not in induced_err_vars:
                induced_err_vars[var2] = []
            induced_err_vars[var1].append(f"err_res_{pair_tag}[..., 0]")
            induced_err_vars[var2].append(f"err_res_{pair_tag}[..., 1]")

            lines.append(f"{ind()}sigma_res_{var1}_{var2} = numpyro.sample('sigma_res_{var1}_{var2}', dist.HalfNormal(2.0))")
            lines.append(f"{ind()}sigma_res_{var2}_{var1} = numpyro.sample('sigma_res_{var2}_{var1}', dist.HalfNormal(2.0))")
            lines.append(f"{ind()}L_corr_{pair_tag} = numpyro.sample('L_corr_{pair_tag}', dist.LKJCholesky(2, concentration=2.0))")
            lines.append(f"{ind()}numpyro.deterministic('rho_{pair_tag}', L_corr_{pair_tag}[1, 0])")
            lines.append(f"{ind()}scale_diag_{pair_tag} = jnp.array([sigma_res_{var1}_{var2}, sigma_res_{var2}_{var1}])")
            lines.append(f"{ind()}L_cov_{pair_tag} = scale_diag_{pair_tag}[:, None] * L_corr_{pair_tag}")
            lines.append(f"{ind()}with numpyro.plate('err_res_{pair_tag}_plate', N, dim=-1):")
            lines.append(f"{ind(2)}z_err_{pair_tag} = numpyro.sample('z_err_{pair_tag}', dist.Normal(0, 1).expand([2]).to_event(1))")
            lines.append(f"{ind()}err_res_{pair_tag} = numpyro.deterministic('err_res_{pair_tag}', jnp.dot(z_err_{pair_tag}, L_cov_{pair_tag}.T))")
        lines.append("")

    for var in topo_order:
        # Deterministic node
        if var in det_terms:
            expr = det_terms[var]["expression"]
            lines.append(f"{ind()}# --- {var} [deterministic] ---")
            lines.append(f"{ind()}computed_vars['{var}'] = {expr}")
            lines.append("")
            continue

        eq = equations_dict.get(var)
        family = families.get(var, "gaussian").lower()

        lines.append(f"{ind()}# --- {var}  (family: {family}) ---")

        if not eq:
            if var not in induced_cor_set:
                lines.append(f"{ind()}computed_vars['{var}'] = {var}  # exogenous observed")
                lines.append("")
                continue
            else:
                eq = {"intercept": True, "fixed": [], "random": []}

        lines.append(f"{ind()}mu_{var} = jnp.zeros(N)")

        # Intercept
        prior_scale = 1.0 if family in ["poisson", "binomial", "bernoulli", "occupancy", "zip", "zinb", "multinomial", "ordinal"] else 2.5
        if eq.get("intercept", True):
            lines.append(f"{ind()}alpha_{var} = numpyro.sample('alpha_{var}', dist.Normal(0, {prior_scale}))")
            lines.append(f"{ind()}mu_{var} = mu_{var} + alpha_{var}")
        else:
            lines.append(f"{ind()}alpha_{var} = 0.0")

        # Fixed effects
        for pred in eq.get("fixed", []):
            is_pred_latent = pred not in [v for v in topo_order if equations_dict.get(v) is None]
            if is_pred_latent and pred not in pinned and builder.fix_latent == "loading":
                lines.append(f"{ind()}# beta_{var}_{pred} fixed to 1.0 (latent loading anchor)")
                lines.append(f"{ind()}mu_{var} = mu_{var} + 1.0 * computed_vars.get('{pred}', {pred})")
                pinned.add(pred)
            else:
                lines.append(f"{ind()}beta_{var}_{pred} = numpyro.sample('beta_{var}_{pred}', dist.Normal(0, {prior_scale}))")
                lines.append(f"{ind()}mu_{var} = mu_{var} + beta_{var}_{pred} * computed_vars.get('{pred}', {pred})")

        # Random effects
        sigma_struct_names = []
        for rand_term in eq.get("random", []):
            import re as _re
            match = _re.search(r"\(1\s*\|\s*([^)]+)\)", rand_term)
            if not match:
                continue
            grp = match.group(1).strip()
            lines.append(f"{ind()}# Random effect: (1 | {grp})")
            lines.append(f"{ind()}sigma_{var}_{grp} = numpyro.sample('sigma_{var}_{grp}', dist.HalfNormal(2.0))")
            lines.append(f"{ind()}with numpyro.plate('{var}_{grp}_plate', N_{grp}):")
            lines.append(f"{ind(2)}z_{var}_{grp}_raw = numpyro.sample('z_{var}_{grp}_raw', dist.Normal(0, 1))")

            if grp in cor_mats:
                mat_info = cor_mats[grp]
                mat_type = mat_info.get("type", "corr") if isinstance(mat_info, dict) else "corr"
                lines.append(f"{ind()}# {mat_type} transform for '{grp}'")
                lines.append(f"{ind()}z_{var}_{grp} = numpyro.deterministic('z_{var}_{grp}', L_{grp} @ z_{var}_{grp}_raw)")
            else:
                lines.append(f"{ind()}z_{var}_{grp} = numpyro.deterministic('z_{var}_{grp}', z_{var}_{grp}_raw)")

            lines.append(f"{ind()}u_{var}_{grp} = numpyro.deterministic('u_{var}_{grp}', z_{var}_{grp} * sigma_{var}_{grp})")
            lines.append(f"{ind()}mu_{var} = mu_{var} + u_{var}_{grp}[{grp}]")
            sigma_struct_names.append(grp)

        if var in induced_err_vars:
            lines.append(f"{ind()}# Add latent induced correlation errors")
            for err_term in induced_err_vars[var]:
                lines.append(f"{ind()}mu_{var} = mu_{var} + {err_term}")

        # Distribution / Likelihood
        lines.append(f"{ind()}# Likelihood")
        if family == "gaussian":
            if var in induced_cor_set:
                lines.append(f"{ind()}# sigma_{var} is already computed via variance partitioning above")
            else:
                lines.append(f"{ind()}sigma_{var} = numpyro.sample('sigma_{var}', dist.HalfNormal(2.0))")
            lines.append(f"{ind()}with numpyro.plate('{var}_plate', N):")
            lines.append(f"{ind(2)}numpyro.sample('{var}', dist.Normal(mu_{var}, sigma_{var}), obs={var})")
            if var not in induced_cor_set:
                for grp in sigma_struct_names:
                    lines.append(f"{ind()}numpyro.deterministic('lambda_{var}_{grp}',")
                    lines.append(f"{ind()}    sigma_{var}_{grp}**2 / (sigma_{var}_{grp}**2 + sigma_{var}**2))")
        elif family == "poisson":
            lines.append(f"{ind()}with numpyro.plate('{var}_plate', N):")
            lines.append(f"{ind(2)}numpyro.sample('{var}', dist.Poisson(rate=jnp.exp(mu_{var})), obs={var})")
        elif family == "binomial":
            lines.append(f"{ind()}with numpyro.plate('{var}_plate', N):")
            lines.append(f"{ind(2)}numpyro.sample('{var}', dist.Bernoulli(logits=mu_{var}), obs={var})")
        elif family == "negbinomial":
            lines.append(f"{ind()}r_{var} = numpyro.sample('r_{var}', dist.Gamma(2.0, 0.1))")
            lines.append(f"{ind()}with numpyro.plate('{var}_plate', N):")
            lines.append(f"{ind(2)}numpyro.sample('{var}', dist.NegativeBinomial2(")
            lines.append(f"{ind(3)}mean=jnp.exp(mu_{var}), concentration=r_{var}), obs={var})")
        else:
            lines.append(f"{ind()}# Family '{family}' — see compiler for full implementation")
            lines.append(f"{ind()}with numpyro.plate('{var}_plate', N):")
            lines.append(f"{ind(2)}numpyro.sample('{var}', dist.Normal(mu_{var}, 1.0), obs={var})")

        lines.append(f"{ind()}computed_vars['{var}'] = mu_{var}")
        lines.append("")

    return "\n".join(lines)
